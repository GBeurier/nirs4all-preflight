import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
import { chromium } from 'playwright-core';

const browser = await chromium.launch({ executablePath: process.env.CHROME ?? '/usr/bin/google-chrome', headless: true, args: ['--no-sandbox'] });
const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } });
const errors = [];
page.on('pageerror', (e) => errors.push(e.message));
const complete = () => page.locator('.ws-status').filter({ hasText: 'Analysis complete' }).waitFor({ timeout: 90000 });
const navigate = (name) => page.locator('.journey').getByRole('button', { name: new RegExp(`^${name}`) }).click();
const download = async (button) => {
  const pending = page.waitForEvent('download');
  await button.click();
  const file = await pending;
  return { name: file.suggestedFilename(), text: await readFile(await file.path(), 'utf8') };
};
try {
  await page.goto(process.env.SMOKE_URL ?? 'http://127.0.0.1:4173/nirs4all-preflight/');
  await page.locator('.demo-card').filter({ hasText: 'Synthetic set with pitfalls' }).click();
  await complete();
  assert.equal(await page.locator('.journey-num').count(), 0);
  assert.equal(await page.locator('.sample-details[open]').count(), 0);
  assert.equal(await page.locator('#data-spectra').getByRole('button', { name: 'batch', exact: true }).count(), 1);
  await page.getByRole('button', { name: 'Settings', exact: true }).click();
  assert.equal(await page.getByLabel('Role of id_sample').inputValue(), 'identifier');
  await page.getByLabel('Role of batch').selectOption('excluded');
  const clustering = page.locator('#settings details').filter({ has: page.getByText('Exploratory groups', { exact: true }) });
  await clustering.locator('summary').click();
  await clustering.getByLabel('Include exploratory groups').uncheck();
  assert.equal(await clustering.locator('tbody tr').count(), 4);
  await page.getByRole('button', { name: 'Re-run analysis', exact: true }).click();
  await complete();
  assert.equal(await page.locator('#data-spectra').getByRole('button', { name: 'batch', exact: true }).count(), 0);
  await navigate('Diagnosis');
  assert.equal(await page.locator('#s-clustering').count(), 0);
  assert.equal(await page.locator('#s-quality [data-reference]').count(), 2);
  assert.match(await page.locator('#s-quality').innerText(), /spectra|Spectra/);
  assert(await page.locator('.diag-side .count').count() > 0);
  const svg = await download(page.locator('#s-quality').getByRole('button', { name: 'Export plot (SVG)', exact: true }).first());
  assert.match(svg.name, /\.svg$/);
  assert.match(svg.text, /data-reference="x"/);
  assert.match(svg.text, /Synthetic set with pitfalls/);
  const csv = await download(page.locator('#s-quality').getByRole('button', { name: 'Export chart table (CSV)', exact: true }).first());
  assert.match(csv.text, /T²/);
  assert.match(csv.text, /Q/);
  await page.screenshot({ path: '/tmp/preflight-review-desktop.png', fullPage: true });
  await page.locator('#s-quality').screenshot({ path: '/tmp/preflight-review-quality.png' });
  await navigate('Evidence');
  assert.equal(await page.locator('.n4q-table td').getByText('source_target', { exact: true }).count(), 0);
  await page.getByRole('button', { name: 'Deselect shown', exact: true }).click();
  const first = page.locator('#s-evidence tbody input[type=checkbox]').first();
  await first.check();
  await page.getByLabel('Family', { exact: true }).selectOption('structure');
  assert(await page.locator('#s-evidence tbody input[type=checkbox]').count() > 0);
  await navigate('Export');
  const report = JSON.parse((await download(page.locator('.export-card').filter({ hasText: 'JSON report' }))).text);
  assert.equal(report.metrics.length, 2);
  assert.equal(report.metrics.filter((m) => m.metric_id === 'analysis.selection').length, 1);
  assert.equal(report.status, 'partial');
  assert(report.limitations.some((l) => /This export includes 2 of .*retaining analysis.selection provenance/.test(l)));
  const html = await download(page.locator('.export-card').filter({ hasText: 'HTML report' }));
  assert.match(html.text, /Scientific metrics and availability/);
  await page.setViewportSize({ width: 375, height: 812 });
  await navigate('Your data');
  await page.screenshot({ path: '/tmp/preflight-review-mobile.png', fullPage: true });
  if (await page.evaluate(() => document.documentElement.scrollWidth > innerWidth + 1)) console.log(await page.evaluate(() => [...document.querySelectorAll('body *')].map((e) => ({ tag: e.tagName, className: e.getAttribute('class'), right: Math.round(e.getBoundingClientRect().right), width: Math.round(e.getBoundingClientRect().width) })).filter((e) => e.right > innerWidth + 1 && e.width > 0).slice(0, 30)));
  assert(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1), 'Narrow layout overflows');
  await page.screenshot({ path: '/tmp/preflight-review-mobile.png', fullPage: true });
  assert.deepEqual(errors, []);
  console.log('Review smoke passed: metadata roles, family selection/timings, inspection limits, alert badges, SVG/CSV downloads, persistent indicator selection, filtered JSON/HTML and mobile layout.');
} finally { await browser.close(); }

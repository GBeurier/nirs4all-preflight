export type TextKey = keyof typeof DICT;

export function isTextKey(key: string): key is TextKey {
  return Object.prototype.hasOwnProperty.call(DICT, key);
}

export function translate(key: TextKey, locale: Locale): string {
  return DICT[key][locale];
}

/** Replaces `{name}` placeholders of a translated string. */
export function fill(text: string, vars: Record<string, string | number>): string {
  return text.replace(/\{(\w+)\}/g, (m, k: string) => (k in vars ? String(vars[k]) : m));
}

export function initialLocale(): Locale {
  return typeof navigator !== "undefined" && navigator.language.toLowerCase().startsWith("en") ? "en" : "fr";
}
